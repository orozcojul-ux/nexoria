function mergePacks(...packs) {
  const out = {};
  for (const pack of packs) {
    for (const [lang, keys] of Object.entries(pack)) {
      out[lang] = { ...(out[lang] || {}), ...keys };
    }
  }
  return out;
}

export const LOCALE_OVERRIDES = mergePacks(SIDEBAR, DASHBOARD, FOOTER);

/** Apply locale-specific string overrides onto merged entries. */
export function applyLocaleOverrides(entries) {
  const out = { ...entries };
  for (const [key, entry] of Object.entries(out)) {
    if (!entry || typeof entry !== "object") continue;
    let patched = entry;
    for (const lang of Object.keys(LOCALE_OVERRIDES)) {
      const text = LOCALE_OVERRIDES[lang][key];
      if (text) patched = { ...patched, [lang]: text };
    }
    out[key] = patched;
  }
  return out;
}
